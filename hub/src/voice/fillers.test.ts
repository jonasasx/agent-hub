// Hesitation sounds in dictation (change voice-input, D3).
import { describe, expect, it } from 'vitest';
import { stripFillers } from './fillers.js';

describe('stripFillers', () => {
  it.each([
    ['Давай, э-э-э, сделаем фильтр.', 'Давай, сделаем фильтр.'],
    ['Давай э-э-э сделаем фильтр.', 'Давай сделаем фильтр.'],
    ['Эээ, давай сделаем.', 'Давай сделаем.'],
    ['Э-э. Давай сделаем.', 'Давай сделаем.'],
    ['Привет. Эм, как дела?', 'Привет. Как дела?'],
    ['Привет. Э-э. Давай.', 'Привет. Давай.'],
    ['Подожди... эм... ладно.', 'Подожди... ладно.'],
    ['Посмотри, ммм, логи.', 'Посмотри, логи.'],
    ['Хм, странно.', 'Странно.'],
    ['Давай, эээ, сделаем фильтр. Эээ, м-м-м-м-м, чтобы он не писал лишнее', 'Давай, сделаем фильтр. Чтобы он не писал лишнее'],
    ['Открой файл, э.', 'Открой файл.'],
    ['Um, open the file, uh, please.', 'Open the file, please.'],
    ['ЭЭЭ Агент упал', 'Агент упал'],
    ['э–э–э', ''],
  ])('%s → %s', (input, expected) => {
    expect(stripFillers(input)).toBe(expected);
  });

  it.each(['Отступ 5 мм, а не 3 мм.', 'Ну вот, а потом типа упало.', 'Этот экран, эмулятор и эмоджи на месте.', 'Секция ЭМ-1 и хмель.', 'Привет. maybe lower case stays', ''])('keeps «%s»', text => {
    expect(stripFillers(text)).toBe(text);
  });
});
